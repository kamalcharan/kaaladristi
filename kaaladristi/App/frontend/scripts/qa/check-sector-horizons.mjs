import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source=fs.readFileSync(new URL('../../src/lib/sectorHorizonStory.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const exports={};new Function('exports',js)(exports);
const {horizonStory,leadershipStory}=exports;
const base={current:{weekly:true,monthly:true,leaders:3,eligible:5,total:5},flow:{state:'Strong',score_5d:74,score_22d:18},status:'Running broadly',aligned_streak:2,aligned_samples:14,known_samples:26};
assert.match(horizonStory(base),/two horizons agree/);
assert.match(horizonStory({...base,flow:{state:'Fading',score_5d:12,score_22d:25}}),/mixed picture/);
assert.match(horizonStory({...base,current:{...base.current,monthly:false}}),/do not both support/);
assert.match(horizonStory({...base,current:{...base.current,weekly:null}}),/not enough evidence/);
assert.match(horizonStory({...base,flow:{state:'Unavailable',score_5d:null,score_22d:18}}),/not enough evidence/);
assert.match(horizonStory({...base,status:'Limited coverage'}),/coverage is limited/);
assert.match(horizonStory(base,'simple'),/22D is a short-term baseline/);
assert.match(horizonStory(base,'detailed'),/Flow 5D: 74.0/);
assert.match(leadershipStory(base,'persistence'),/2 completed weeks/);
assert.match(leadershipStory(base,'persistence'),/14 of 26/);
assert.match(leadershipStory(base,'breadth','simple'),/different from stocks rising today/);
console.log('PASS: horizon agreement, disagreement, missing data, limited coverage, depth and persistence semantics');
