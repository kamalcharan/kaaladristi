import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const base = process.env.QA_BASE_URL ?? 'http://localhost:5174';
const browser = await chromium.launch({ channel: process.env.QA_BROWSER_CHANNEL ?? 'msedge', headless: true });
try {
  for (const width of [1440, 390]) for (const mode of ['light', 'dark']) {
    const page = await browser.newPage({ viewport: { width, height: 1000 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.route('**/*', route => {
      const url = new URL(route.request().url());
      if (url.pathname.startsWith('/db/') || url.pathname.startsWith('/pipeline-api/')) return route.fulfill({ json: [] });
      if (url.origin === new URL(base).origin) return route.continue();
      return route.abort();
    });
    await page.goto(`${base}/scripts/qa/fixtures/story-route.html?mode=${mode}`);
    await page.getByRole('heading', { name: 'Turning points, in time' }).waitFor();
    assert.equal(await page.getByText('Current market cap', { exact: true }).count(), 1);
    for (const id of ['story-events', 'story-watch', 'story-conditions']) assert.equal(await page.locator(`#${id}`).count(), 1);
    assert.equal(await page.locator('#story-price').count(), 0);
    assert.equal(await page.locator('#story-leadership').count(), 0);
    assert.equal(await page.locator('#story-participation').count(), 0);
    assert.equal(await page.locator('#story-events').evaluate(el => el.parentElement.nextElementSibling?.id), 'story-conditions');
    const setup = page.getByRole('region', { name: 'Setup Read', exact: true });
    for (const heading of ['Current Situation', 'Long-Term Lens', 'Swing Lens', 'What Confirms This Setup']) await setup.getByRole('heading', { name: heading, exact: true }).waitFor();
    await setup.getByText(/Editor's Note/).waitFor();
    assert.equal(await setup.locator('.story-condition-grid').count(), 0);
    assert.notEqual(await setup.evaluate(el => getComputedStyle(el).backgroundColor), await page.locator('.story-panel').first().evaluate(el => getComputedStyle(el).backgroundColor));
    assert.ok(!/\b(bull|bear|bullish|bearish|uptrend|downtrend)\b/i.test(await page.locator('.stock-story').innerText()));
    await page.screenshot({ path: join(process.env.QA_OUTPUT ?? tmpdir(), `analysis-${width}-${mode}.png`), fullPage: true });
    const markers = page.locator('.story-time-event');
    const selectedDate = await markers.first().locator('time').getAttribute('datetime');
    await markers.first().click();
    assert.ok((await page.locator('.story-day-heading').innerText()).includes(selectedDate));
    await page.getByLabel('Timeline window').selectOption('14');
    const anchors = await page.locator('.story-time-anchor').evaluateAll(items => items.map(el => ({ date: el.dataset.date, top: el.style.top })));
    for (const a of anchors) assert.ok(anchors.filter(b => b.date === a.date).every(b => b.top === a.top));
    await page.getByRole('button', { name: '← Earlier', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Later →', exact: true }).isEnabled(), true);
    await page.getByRole('button', { name: 'Later →', exact: true }).click();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.getByRole('button', { name: 'Relative strength', exact: true }).click();
    await page.getByRole('button', { name: 'Locate candle →' }).first().click();
    await page.getByRole('button', { name: 'Clear focus' }).waitFor();
    await page.locator('#story-price canvas').first().waitFor();
    assert.equal(await page.getByRole('tab', { name: 'Chart & Replay', exact: true }).getAttribute('aria-selected'), 'true');
    for (const id of ['story-price', 'story-leadership', 'story-participation']) assert.equal(await page.locator(`#${id}`).count(), 1);
    assert.equal(await page.locator('#story-conditions').count(), 0);
    assert.ok((await page.locator('.story-selection').innerText()).includes('Chart focus'));
    await page.getByRole('button', { name: 'Clear focus' }).click();
    assert.equal(await page.locator('.story-selection').count(), 0);
    await page.getByRole('button', { name: '▷ Play story', exact: true }).click();
    await page.getByRole('button', { name: '❚❚ Pause', exact: true }).waitFor();
    await page.getByRole('button', { name: '❚❚ Pause', exact: true }).click();
    await page.evaluate(() => window.scrollTo(0, 0));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Overflow ${width} ${mode}`);
    await page.screenshot({ path: join(process.env.QA_OUTPUT ?? tmpdir(), `story-${width}-${mode}.png`), fullPage: true });
    await page.getByRole('tab', { name: 'Analysis', exact: true }).click();
    await page.getByRole('region', { name: 'Setup Read', exact: true }).waitFor();
    await page.getByRole('tab', { name: 'Analysis', exact: true }).press('ArrowRight');
    await page.locator('#story-price canvas').first().waitFor();
    await page.getByRole('tab', { name: 'Chart & Replay', exact: true }).press('Home');
    await page.getByRole('region', { name: 'Setup Read', exact: true }).waitFor();
    await page.getByRole('tab', { name: 'Data', exact: true }).click();
    const dataPanel = page.getByRole('tabpanel', { name: 'Data', exact: true });
    await dataPanel.getByRole('button', { name: /Columns/ }).click();
    await dataPanel.getByRole('button', { name: 'Reset to default', exact: true }).waitFor();
    await dataPanel.getByRole('button', { name: /Columns/ }).click();
    await dataPanel.getByRole('button', { name: 'CSV', exact: true }).waitFor();
    assert.equal(await page.locator('#story-conditions').count(), 0);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: join(process.env.QA_OUTPUT ?? tmpdir(), `data-${width}-${mode}.png`), fullPage: true });
    await page.getByRole('tab', { name: 'Data', exact: true }).press('Home');
    await page.getByRole('region', { name: 'Setup Read', exact: true }).waitFor();
    await page.goto(`${base}/scripts/qa/fixtures/story-route.html?mode=${mode}&missing=1`);
    await page.getByRole('heading', { name: 'Turning points, in time' }).waitFor();
    assert.equal(await page.getByText('Current market cap', { exact: true }).count(), 0);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    assert.deepEqual(errors, []);
    console.log(`PASS actual StockStoryPage route · ${width}px · ${mode} · chart focus/filter · absent MCAP · no overflow`);
    await page.close();
  }
} finally { await browser.close(); }
